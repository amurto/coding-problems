int solve()
{
    int n;
    cin >> n;
    vector<int> arr(n);
    for (int i = 0; i < n; i++)
        cin >> arr[i];
    for (int i = 1; i < n; i++)
        if (arr[i - 1] >= arr[i])
            return arr[i - 1];
    return arr[n - 1];
}

